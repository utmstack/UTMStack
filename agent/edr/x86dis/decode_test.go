// answer formats a Decode result the way the oracle prints the reference's.
func answer(rec [64]byte, n int, ok bool) string {
	if !ok {
		return "fail"
	}
	return "ok " + strconv.Itoa(n) + " " + hex.EncodeToString(rec[:])
}

func checkAgainst(t *testing.T, input, want string) bool {
	t.Helper()
	buf, err := hex.DecodeString(input)
	if err != nil {
		t.Fatalf("bad input %q: %v", input, err)
	}
	got := answer(Decode(buf))
	if got != strings.TrimSpace(want) {
		t.Errorf("Decode(%s):\n got %s\nwant %s", input, got, want)
		return false
	}
	return true
}

func TestDecodeGolden(t *testing.T) {
	for _, c := range goldenCases {
		checkAgainst(t, c.in, c.want)
	}
}

func TestDecodeReadsOnlyTheBuffer(t *testing.T) {
	// A full instruction followed by nothing decodes; the same bytes cut by one
	// fail rather than read past the end.
	full, _ := hex.DecodeString("8b048d00104000")
	if _, n, ok := Decode(full); !ok || n != len(full) {
		t.Fatalf("full instruction: ok=%v n=%d", ok, n)
	}
	for cut := 0; cut < len(full); cut++ {
		if _, _, ok := Decode(full[:cut]); ok {
			t.Errorf("instruction cut to %d bytes decoded", cut)
		}
	}
}
