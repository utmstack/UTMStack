package unpack

import "encoding/binary"

// The reference scanner's PESpin unpacker for the PESpin version of the
// upstream test program, learned from its debug lines and rebuilt programs on
// that program, on an inversion of each of its bytes (once as is, once with
// the stored key adjusted for the file checksum) and on variants built with
// its layers re-encrypted (docs/edr/native-engine/parity/unpackers.md section
// 8; lab scripts in docs/2026-10-15-pespin/). The packer's stub, run in an
// emulator, showed the layers; the reference undoes them at fixed offsets
// from the entry point, on a copy of the file:
//
//   - 0x11fe bytes from entry+0x1fe5, from the last down, XORed with a byte
//     key read at entry+0xdc that drops by one per byte ("Key8"); the
//     instruction bytes around it (mov ebx, mov ecx, 0x11fe) must hold;
//   - 0x5a0 bytes from entry+0x2d5 ("Key", at entry+0x26eb; the length at
//     entry+0x26f0 must be 0x5a0) and 0x180 bytes from entry+0x28d3 ("Key"
//     at entry+0x650; the length at entry+0x644 must be 0x180) XORed with the
//     low byte of a register shifted right once per byte and XORed with
//     0x8c328834 or 0xed43af32 when the bit shifted out is 1;
//   - each section in the bitmap at entry+0x3207 (all but the stub's) XORed
//     the same way with 0xed43af31 when the bit shifted out is 0, from a key
//     that is the dword at entry+0x3217 less the stub's checksum of the file
//     without its last bytes (their count at entry+0x429);
//   - two generated byte decryptors, each 0x24 bytes of operations ending in
//     stosb, run by a small emulator: POLY1's (at entry+0x28ec, over 0x1a1
//     bytes from entry+0x6d4; that length at entry+0x28dd must be 0x1a1),
//     then the sections' (at entry+0x755) over each section in the bitmap at
//     entry+0x6f1; the counter runs from the length down;
//   - each section in the bitmap at entry+0x3061 depacked with aPLib into
//     its virtual size.
//
// The program is rebuilt from the sections but the stub's, each as large as
// its raw size or, when depacked, its virtual size, with entry point 0x1000
// and image base 0x400000 whatever the program says (no header or stub byte
// changed them).

// PESpinOutcome is what the reference's parser does at the PESpin step.
type PESpinOutcome uint8

const (
	// PESpinGoesOn: unpacking failed; the parser goes on.
	PESpinGoesOn PESpinOutcome = iota
	// PESpinUnpacked: a rebuilt program, scanned as a child; the parser then
	// returns.
	PESpinUnpacked
	// PESpinUnknown: this engine cannot tell.
	PESpinUnknown
)

// PESpinSection is a section as the parser keeps it: address and virtual
// size aligned to the section alignment, raw pointer and size within the
// file.
type PESpinSection struct {
	RVA, VSize, Raw, RawSize uint32
}

// PESpinProgram is what the PESpin step reads: the file, the entry point's
// file offset and the parser's sections (the last holds the stub).
type PESpinProgram struct {
	File     []byte
	Entry    int
	Sections []PESpinSection
}

const (
	pespinLen8  = 0x11fe
	pespinLenA  = 0x5a0
	pespinLenB  = 0x180
	pespinPoly1 = 0x1a1
	pespinCode  = 0x24 // a decryptor's operations before its stosb
)

// PESpin runs the reference's PESpin step. The outcome is PESpinUnknown where
// the program leaves the checked layout: a stub too close to the file's end,
// more sections than a bitmap holds, a section to depack without a virtual
// size, or sections whose data the reference's parser keeps elsewhere.
func PESpin(p PESpinProgram) (PESpinOutcome, []byte) {
	le := binary.LittleEndian
	f := p.File
	n := len(p.Sections)
	ep := p.Entry
	if n < 2 || n-1 > 32 || ep < 0 || ep+0x3217+4 > len(f) {
		return PESpinUnknown, nil
	}
	for _, s := range p.Sections {
		if uint64(s.Raw)+uint64(s.RawSize) > uint64(len(f)) {
			return PESpinUnknown, nil
		}
	}
	img := append([]byte(nil), f...)
	u32 := func(at int) uint32 { return le.Uint32(img[at:]) }
	if img[ep+0xdb] != 0xbb || img[ep+0xe0] != 0xb9 || u32(ep+0xe1) != pespinLen8 {
		return PESpinGoesOn, nil // "Not spinned or bad version"
	}
	k := img[ep+0xdc]
	for i := pespinLen8; i > 0; i-- {
		img[ep+0x1fe4+i] ^= k
		k--
	}
	if u32(ep+0x26f0) != pespinLenA {
		return PESpinGoesOn, nil
	}
	pespinStream(img[ep+0x2d5:ep+0x2d5+pespinLenA], u32(ep+0x26eb), 0x8c328834, 1)
	adj := u32(ep + 0x429)
	if uint64(adj) > uint64(len(f)) {
		return PESpinGoesOn, nil // "crc out of bounds"
	}
	key := u32(ep+0x3217) - pespinChecksum(f[:len(f)-int(adj)])
	sections := p.Sections[:n-1]
	data := func(s PESpinSection) []byte { return img[s.Raw : s.Raw+s.RawSize] }
	xor := u32(ep + 0x3207)
	for j, s := range sections {
		if xor>>j&1 != 0 {
			pespinStream(data(s), key, 0xed43af31, 0)
		}
	}
	if u32(ep+0x644) != pespinLenB {
		return PESpinGoesOn, nil
	}
	pespinStream(img[ep+0x28d3:ep+0x28d3+pespinLenB], u32(ep+0x650), 0xed43af32, 1)
	if u32(ep+0x28dd) != pespinPoly1 {
		return PESpinGoesOn, nil
	}
	if !pespinEmulate(img[ep+0x28ec:ep+0x28ec+pespinCode+1], img[ep+0x6d4:ep+0x6d4+pespinPoly1]) {
		return PESpinGoesOn, nil // "cannot exec poly1"
	}
	poly := u32(ep + 0x6f1)
	for j, s := range sections {
		if poly>>j&1 != 0 && !pespinEmulate(img[ep+0x755:ep+0x755+pespinCode+1], data(s)) {
			return PESpinGoesOn, nil // "cannot exec section"
		}
	}
	packed := u32(ep + 0x3061)
	var out []RebuildSection
	failed := false
	for j, s := range sections {
		if packed>>j&1 == 0 {
			out = append(out, RebuildSection{RVA: s.RVA, VSize: s.VSize, RawSize: s.RawSize, Data: data(s)})
			continue
		}
		if s.VSize == 0 || s.VSize > 64<<20 {
			return PESpinUnknown, nil
		}
		d, ok := aplibDepack(data(s), int(s.VSize))
		if !ok {
			failed = true // "Unpack failure"; the other sections are still tried
			continue
		}
		out = append(out, RebuildSection{RVA: s.RVA, VSize: s.VSize, RawSize: s.VSize, Data: d})
	}
	if failed {
		return PESpinGoesOn, nil
	}
	if len(out) == 0 || out[0].RVA < 0x1000 {
		return PESpinUnknown, nil
	}
	if out[0].RVA > 0x1000 {
		out = append([]RebuildSection{{RVA: 0x1000, VSize: out[0].RVA - 0x1000, Empty: true}}, out...)
	}
	return PESpinUnpacked, Rebuild(out, 0x1000, 0x400000, 0, 0)
}

// pespinStream XORs b with the low byte of a register shifted right once per
// byte and XORed with poly when the bit shifted out equals one.
func pespinStream(b []byte, key, poly, one uint32) {
	for i := range b {
		bit := key & 1
		key >>= 1
		if bit == one {
			key ^= poly
		}
		b[i] ^= byte(key)
	}
}

// pespinChecksum is the stub's checksum of its own file.
func pespinChecksum(b []byte) uint32 {
	eax, ebx := uint32(0xffffffff), uint32(0xffffffff)
	for _, x := range b {
		eax ^= uint32(x) << 8
		eax >>= 3
		for i := 0; i < 4; i++ {
			eax = eax&^0xff | (eax^ebx>>8)&0xff
			eax += 0x7801a108
			eax ^= ebx
			c := ebx & 31
			eax = eax>>c | eax<<(32-c)
			eax, ebx = ebx, eax
		}
	}
	return ebx
}

// pespinEmulate runs a generated decryptor, code being its 0x24 bytes of
// operations and the stosb after them, on b. The reference's emulator knows
// add, sub and xor with a constant (04, 2c, 34) or the counter (02, 2a, 32,
// whatever the second byte), increment (fe c0) and decrement (any other fe),
// rotation by a constant (c0 c0 left, any other c0 right; the count modulo
// 8), or al,al (0a), nop, clc and stc, and a jump over one byte (eb, always
// three bytes); any other byte, or no stosb right after the 0x24 bytes,
// fails.
func pespinEmulate(code, b []byte) bool {
	type op struct{ code, arg byte }
	var ops []op
	p := 0
	for p < pespinCode {
		c := code[p]
		switch c {
		case 0x04, 0x2c, 0x34, 0xfe:
			ops = append(ops, op{c, code[p+1]})
			p += 2
		case 0x02, 0x2a, 0x32:
			ops = append(ops, op{c, 0})
			p += 2
		case 0x0a:
			p += 2
		case 0xc0:
			if p+3 > pespinCode {
				return false // runs past the stosb: "bad emucode"
			}
			left := byte(0xc8)
			if code[p+1] == 0xc0 {
				left = 0xc0
			}
			ops = append(ops, op{left, code[p+2] & 7})
			p += 3
		case 0x90, 0xf8, 0xf9:
			p++
		case 0xeb:
			p += 3
		default:
			return false // "bogus opcode"
		}
		if p > pespinCode {
			return false
		}
	}
	if code[pespinCode] != 0xaa {
		return false // "bad emucode"
	}
	n := len(b)
	for i := range b {
		al, cl := b[i], byte(n-i)
		for _, o := range ops {
			switch o.code {
			case 0x04:
				al += o.arg
			case 0x2c:
				al -= o.arg
			case 0x34:
				al ^= o.arg
			case 0x02:
				al += cl
			case 0x2a:
				al -= cl
			case 0x32:
				al ^= cl
			case 0xfe:
				if o.arg == 0xc0 {
					al++
				} else {
					al--
				}
			case 0xc0:
				al = al<<o.arg | al>>(8-o.arg)
			case 0xc8:
				al = al>>o.arg | al<<(8-o.arg)
			}
		}
		b[i] = al
	}
	return true
}

// aplibDepack depacks aPLib data into at most limit bytes; it fails on a read
// past src, a write past limit or a match from before the output's start. A
// match at offset 0 copies the output's unwritten (zero) bytes, as the
// reference's does.
func aplibDepack(src []byte, limit int) ([]byte, bool) {
	out := make([]byte, 0, limit)
	pos, tag, bits := 0, byte(0), 0
	bad := false
	next := func() byte {
		if pos >= len(src) {
			bad = true
			return 0
		}
		pos++
		return src[pos-1]
	}
	bit := func() int {
		if bits == 0 {
			tag, bits = next(), 8
		}
		bits--
		b := int(tag >> 7)
		tag <<= 1
		return b
	}
	gamma := func() int {
		v := 1
		for {
			v = v<<1 + bit()
			if bad || v > 1<<30 {
				bad = true
				return 0
			}
			if bit() == 0 {
				return v
			}
		}
	}
	copyMatch := func(off, length int) bool {
		if off > len(out) || length > limit-len(out) {
			return false
		}
		for i := 0; i < length; i++ {
			if off == 0 {
				out = append(out, 0)
			} else {
				out = append(out, out[len(out)-off])
			}
		}
		return true
	}
	if limit < 1 {
		return nil, false
	}
	out = append(out, next())
	lwm, r0 := 0, 0
	for !bad {
		switch {
		case bit() == 0:
			if len(out) >= limit {
				return nil, false
			}
			out = append(out, next())
			lwm = 0
		case bit() == 0:
			off := gamma()
			if lwm == 0 && off == 2 {
				if l := gamma(); bad || !copyMatch(r0, l) {
					return nil, false
				}
			} else {
				if lwm == 0 {
					off -= 3
				} else {
					off -= 2
				}
				off = off<<8 + int(next())
				l := gamma()
				if off >= 32000 {
					l++
				}
				if off >= 1280 {
					l++
				}
				if off < 128 {
					l += 2
				}
				if bad || !copyMatch(off, l) {
					return nil, false
				}
				r0 = off
			}
			lwm = 1
		case bit() == 0:
			b := int(next())
			off, l := b>>1, 2+b&1
			if bad {
				return nil, false
			}
			if off == 0 {
				return out, true
			}
			if !copyMatch(off, l) {
				return nil, false
			}
			r0, lwm = off, 1
		default:
			off := 0
			for i := 0; i < 4; i++ {
				off = off<<1 | bit()
			}
			if len(out) >= limit || off > len(out) {
				return nil, false
			}
			if off == 0 {
				out = append(out, 0)
			} else {
				out = append(out, out[len(out)-off])
			}
			lwm = 0
		}
	}
	return nil, false
}
